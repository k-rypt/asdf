-- supabase/migrations/2026-10-10_preset_approvals.sql
begin;

create table public.preset_approvals (
  id bigint generated by default as identity primary key,
  preset_id bigint not null references public.question_presets(id) on delete cascade,
  action text not null check (action in ('submitted', 'approved', 'rejected')),
  note text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.preset_approvals enable row level security;

create policy "Allow authenticated select"
  on public.preset_approvals for select
  to authenticated
  using (auth.role() = 'authenticated');

-- Mirrors question_preset_questions' write policy exactly. Narrower
-- per-action checks (reject/approve admin-only, submit requires
-- draft/rejected status) are app-layer -- this codebase's established
-- pattern is broad RLS + narrow app checks, not per-action RLS.
create policy "Admin or capability owner can manage preset approvals"
  on public.preset_approvals for all
  to authenticated
  using (
    exists (
      select 1 from profile_roles pr
      join roles r on pr.profile_role = r.id
      where pr.profile_id = (select auth.uid())
        and r.name = any (array['admin', 'capability owner'])
    )
  )
  with check (
    exists (
      select 1 from profile_roles pr
      join roles r on pr.profile_role = r.id
      where pr.profile_id = (select auth.uid())
        and r.name = any (array['admin', 'capability owner'])
    )
  );

-- Current status is always derived from history, never cached, so it
-- can't drift. A preset_id with zero rows has no row here -- the app
-- treats "no row" as 'draft'.
create view public.preset_current_status
with (security_invoker = true)
as
select distinct on (preset_id)
  preset_id,
  action as status,
  note,
  created_by,
  created_at
from public.preset_approvals
order by preset_id, created_at desc;

-- Lock-after-approval: preset edits happen via direct client-side
-- Supabase calls (preset-detail-dialog.tsx), not an API route, so there
-- is no route to add an app-layer check to. These restrictive policies
-- AND with the broad "manage" policies on question_presets /
-- question_preset_questions (see 2026-09-24_question_preset_questions.sql
-- and 2026-09-24_question_presets_description_and_created_by.sql), so an
-- approved preset's rows become un-updatable / un-deletable even though
-- those broad policies would otherwise allow it. Queries preset_approvals
-- directly (not the view) to avoid any RLS-through-a-view subtlety.
create policy "Approved presets cannot be updated"
  on public.question_presets as restrictive
  for update
  to authenticated
  using (
    (
      select pa.action from public.preset_approvals pa
      where pa.preset_id = question_presets.id
      order by pa.created_at desc
      limit 1
    ) is distinct from 'approved'
  );

create policy "Approved presets cannot be deleted"
  on public.question_presets as restrictive
  for delete
  to authenticated
  using (
    (
      select pa.action from public.preset_approvals pa
      where pa.preset_id = question_presets.id
      order by pa.created_at desc
      limit 1
    ) is distinct from 'approved'
  );

create policy "Approved preset questions cannot be inserted"
  on public.question_preset_questions as restrictive
  for insert
  to authenticated
  with check (
    (
      select pa.action from public.preset_approvals pa
      where pa.preset_id = question_preset_questions.preset_id
      order by pa.created_at desc
      limit 1
    ) is distinct from 'approved'
  );

create policy "Approved preset questions cannot be deleted"
  on public.question_preset_questions as restrictive
  for delete
  to authenticated
  using (
    (
      select pa.action from public.preset_approvals pa
      where pa.preset_id = question_preset_questions.preset_id
      order by pa.created_at desc
      limit 1
    ) is distinct from 'approved'
  );

commit;
