-- One self-assessment ladder per capability.
-- Spec: docs/superpowers/specs/2026-10-24-add-questions-and-capability-ladder-design.md
--
-- capability_ladder_levels is the editable ladder. assessment_tiers stays
-- as each assessment's frozen copy (lib/assessment/sync-assessment-tiers.ts
-- re-copies it while the assessment is still editable), so the attempt
-- engine and finished attempts keep reading assessment_tiers unchanged.
--
-- Run ONCE in the Supabase SQL Editor, then run
-- supabase/tests/2026-10-24_capability_ladder_check.sql.
-- Undo with 2026-10-24_capability_ladder_rollback.sql.

begin;

create table public.capability_ladder_levels (
  id bigint generated by default as identity primary key,
  capability_id bigint not null references public.capabilities(id) on delete cascade,
  sfia_level integer not null check (sfia_level between 1 and 7),
  label text not null check (length(btrim(label)) > 0),
  applies_to text,
  pass_threshold numeric not null default 0.6 check (pass_threshold >= 0 and pass_threshold <= 1),
  advance_message text,
  stay_message text,
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles(id) on delete set null,
  unique (capability_id, sfia_level)
);

alter table public.capability_ladder_levels enable row level security;

-- Same broad read as assessment_tiers: anyone signed in.
create policy "Authenticated read ladder levels" on public.capability_ladder_levels
  for select to authenticated
  using (true);

create policy "Capability managers insert ladder levels" on public.capability_ladder_levels
  for insert to authenticated
  with check (public.can_manage_capability(capability_id));
create policy "Capability managers update ladder levels" on public.capability_ladder_levels
  for update to authenticated
  using (public.can_manage_capability(capability_id))
  with check (public.can_manage_capability(capability_id));
create policy "Capability managers delete ladder levels" on public.capability_ladder_levels
  for delete to authenticated
  using (public.can_manage_capability(capability_id));

-- Starting ladder: for each capability and level, the settings from the
-- newest assessment (highest id) that has a tier at that level. Existing
-- assessment_tiers rows are left exactly as they are.
insert into public.capability_ladder_levels
  (capability_id, sfia_level, label, applies_to, pass_threshold, advance_message, stay_message)
select distinct on (a.capability_id, t.sfia_level)
  a.capability_id, t.sfia_level, t.label, t.applies_to, t.pass_threshold, t.advance_message, t.stay_message
from public.assessment_tiers t
join public.assessments a on a.id = t.assessment_id
where a.capability_id is not null
  and t.sfia_level between 1 and 7
order by a.capability_id, t.sfia_level, a.id desc;

commit;
