-- notifications holds five event types in one table so a single read
-- path (GET /api/notifications) and a single NotificationBell component
-- serve both the employee window-reminder family and the manager
-- completion-notice family. assessment_id is assessments.id (the
-- definition employee deep-links key on); attempt_id is attempts.id
-- (the manager review deep-link keys on), populated only on
-- attempt_completed rows -- see the spec's Section 4.
--
-- Idempotency needs two *partial* unique indexes, not one plain
-- composite constraint: Postgres treats NULL <> NULL in uniqueness
-- checks, so a single `unique (profile_id, type, assessment_id)` would
-- never deduplicate attempt_completed rows (which vary by attempt_id,
-- not assessment_id, per completion). Every write against these
-- partial indexes must use a plain .insert() and catch 23505 --
-- supabase-js's upsert(on_conflict=...) cannot restate a partial
-- index's WHERE predicate, so ON CONFLICT inference fails outright
-- against a partial index. See the spec's Section 5 "Why .insert(),
-- not .upsert()".
--
-- No insert policy: every write goes through a service-role client
-- (lib/supabase/service-role-client.ts), matching the posture
-- calibrate-question.ts already established for writes that cross the
-- employee/manager boundary the per-request client's RLS can't satisfy.

begin;

create table public.notifications (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  type text not null check (
    type in ('upcoming', 'active_started', 'active_midpoint', 'active_due_soon', 'attempt_completed')
  ),
  assessment_id bigint references public.assessments(id) on delete cascade,
  attempt_id bigint references public.attempts(id) on delete cascade,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create unique index notifications_window_type_unique
  on public.notifications (profile_id, type, assessment_id)
  where attempt_id is null;

create unique index notifications_attempt_completed_unique
  on public.notifications (profile_id, attempt_id)
  where type = 'attempt_completed';

alter table public.notifications enable row level security;

create policy "Profiles can view their own notifications"
  on public.notifications for select
  to authenticated
  using (profile_id = (select auth.uid()));

create policy "Profiles can mark their own notifications read"
  on public.notifications for update
  to authenticated
  using (profile_id = (select auth.uid()))
  with check (profile_id = (select auth.uid()));

commit;
