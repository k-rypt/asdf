-- The durable record of "this employee's window on this assessment
-- closed without a completed attempt", written lazily by
-- lib/assessment/deadline-flags.ts (Task 10) as a side effect of the
-- manager page (Task 11) or capability-owner overdue list (Task 12)
-- loading -- this app has no cron/background job runner, so there's no
-- other trigger. See the spec's "Deadline-flag upsert mechanism".
--
-- unique (assessment_id, profile_id) is what makes the upsert idempotent
-- (on conflict do nothing) -- an employee's overdue flag is written once,
-- not once per page load, and flagged_at always reflects the *first*
-- time it was detected.
--
-- Select/write RLS needs three audiences: admin, capability owner (same
-- role check as requireCapabilityAdminClient), and a manager viewing
-- their own direct reports' rows -- a manager is neither admin nor
-- capability owner, so this needs a new policy shape checking
-- profile_departments for a shared department where the caller has
-- status = 'management'. No update policy: the upsert is always
-- `on conflict do nothing`, so nothing ever needs UPDATE on this table.

begin;

create table public.assessment_deadline_flags (
  id bigint generated by default as identity primary key,
  assessment_id bigint not null references public.assessments(id) on delete cascade,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  capability_id bigint not null references public.capabilities(id) on delete cascade,
  flagged_at timestamptz not null default now(),
  unique (assessment_id, profile_id)
);

alter table public.assessment_deadline_flags enable row level security;

create policy "Admin, capability owner, or the profile's manager can view deadline flags"
  on public.assessment_deadline_flags for select
  to authenticated
  using (
    exists (
      select 1 from profile_roles pr
      join roles r on pr.profile_role = r.id
      where pr.profile_id = (select auth.uid())
        and r.name = any (array['admin', 'capability owner'])
    )
    or exists (
      select 1 from profile_departments pd
      where pd.profile_id = (select auth.uid())
        and pd.status = 'management'
        and pd.department_id in (
          select department_id from profile_departments
          where profile_id = assessment_deadline_flags.profile_id
        )
    )
  );

create policy "Admin, capability owner, or the profile's manager can write deadline flags"
  on public.assessment_deadline_flags for insert
  to authenticated
  with check (
    exists (
      select 1 from profile_roles pr
      join roles r on pr.profile_role = r.id
      where pr.profile_id = (select auth.uid())
        and r.name = any (array['admin', 'capability owner'])
    )
    or exists (
      select 1 from profile_departments pd
      where pd.profile_id = (select auth.uid())
        and pd.status = 'management'
        and pd.department_id in (
          select department_id from profile_departments
          where profile_id = assessment_deadline_flags.profile_id
        )
    )
  );

commit;
