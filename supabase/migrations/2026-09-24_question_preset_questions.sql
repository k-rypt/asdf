  -- Mirrors public.assessment_questions exactly (same shape, same RLS
  -- pattern) -- see 2026-09-21_assessment_toolkit_schema.sql Step 4 for the
  -- precedent this copies. Links a question_presets row to the actual
  -- questions that make it up, which didn't exist before this migration --
  -- question_presets had metadata columns (duration_minutes/passing_score/
  -- question_type_mix) but nothing tying it to real question rows.

  begin;

  create table if not exists public.question_preset_questions (
    id bigint generated by default as identity primary key,
    preset_id bigint not null references public.question_presets(id) on delete cascade,
    question_id uuid not null references public.questions(id) on delete cascade,
    position integer not null default 0,
    unique (preset_id, question_id)
  );

  alter table public.question_preset_questions enable row level security;

  create policy "Allow authenticated select"
    on public.question_preset_questions for select
    to public
    using (auth.role() = 'authenticated');

  create policy "Admin or capability owner can manage preset questions"
    on public.question_preset_questions for all
    to authenticated
    using (
      exists (
        select 1 from profile_roles pr
        join roles r on pr.profile_role = r.id
        where pr.profile_id = (select auth.uid())
          and r.name = any (array['admin', 'capability owner'])
      )
    )
    with check (
      exists (
        select 1 from profile_roles pr
        join roles r on pr.profile_role = r.id
        where pr.profile_id = (select auth.uid())
          and r.name = any (array['admin', 'capability owner'])
      )
    );

  commit;
