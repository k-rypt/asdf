  -- Adds support for the "tiered self-assessment ladder" yes_no format
  -- (see the Web Developer Assessment example: P1..P5 tiers, each a batch
  -- of yes/no questions gated behind a >=60% "yes" threshold to advance,
  -- with a stay/recommendation message otherwise).
  --
  -- Depends on schema_02_question_enums.sql having been run first (the
  -- 'yes_no' question_type value must already exist before questions of
  -- that type can be inserted, though this migration itself doesn't
  -- reference the enum value directly).
  --
  -- Run this AFTER 2026-09-21_assessment_toolkit_schema.sql (needs the
  -- `assessments` and `attempts` tables to already exist).

  begin;

  -- ---------------------------------------------------------------------
  -- One row per tier (P1..P5) within an assessment. `sfia_level` ties a
  -- tier to the yes_no questions that belong to it via questions.sfia_level
  -- -- no separate FK needed since assessment_questions already links
  -- questions to this assessment.
  -- ---------------------------------------------------------------------
  create table if not exists public.assessment_tiers (
    id bigint generated by default as identity primary key,
    assessment_id bigint not null references public.assessments(id) on delete cascade,
    sfia_level integer not null,
    label text not null, -- e.g. "P1 -- Beginner / Follow"
    applies_to text, -- e.g. "Management Trainee/Intern/Junior Web Developer"
    pass_threshold numeric not null default 0.6, -- >=60% "yes" answers to advance
    advance_message text, -- e.g. "Proceed to P2"
    stay_message text, -- e.g. "Stay at P1 or recommend foundational training"
    position integer not null default 0,
    unique (assessment_id, sfia_level)
  );

  alter table public.assessment_tiers enable row level security;

  -- Matches the broad-read house style (questions/question_choices/assessment_questions).
  create policy "Allow authenticated select"
    on public.assessment_tiers for select
    to public
    using (auth.role() = 'authenticated');

  -- Matches the admin/capability-owner write-gating used on
  -- questions/assessment_questions.
  create policy "Admin or capability owner can manage assessment tiers"
    on public.assessment_tiers for all
    to authenticated
    using (
      exists (
        select 1 from profile_roles pr
        join roles r on pr.profile_role = r.id
        where pr.profile_id = (select auth.uid())
          and r.name = any (array['admin', 'capability owner'])
      )
    )
    with check (
      exists (
        select 1 from profile_roles pr
        join roles r on pr.profile_role = r.id
        where pr.profile_id = (select auth.uid())
          and r.name = any (array['admin', 'capability owner'])
      )
    );

  -- ---------------------------------------------------------------------
  -- Raw answer storage -- attempt_answers currently only stores computed
  -- scores, never the actual answer given. One flexible jsonb column
  -- covers all three question types instead of three mostly-empty typed
  -- columns, matching how this schema already uses jsonb elsewhere
  -- (tags, expected_concepts, irt_b_thresholds):
  --   yes_no          -> {"value": true}
  --   multiple_choice / true_false -> {"selectedChoiceId": "<question_choices.id>"}
  --   code_snippet    -> {"code": "...", "compilationOutput": "..."}
  -- ---------------------------------------------------------------------
  alter table public.attempt_answers
    add column if not exists raw_answer jsonb;

  -- ---------------------------------------------------------------------
  -- Final rollup for ladder-style (yes_no) assessments -- null for
  -- code_snippet/multiple_choice assessments, which use attempts.passed
  -- instead.
  -- ---------------------------------------------------------------------
  alter table public.attempts
    add column if not exists tier_result jsonb; -- e.g. {"achievedSfiaLevel": 2, "message": "Stay at P2 or assign guided projects", "tiers": [...]} -- rows written before the camelCase refactor may carry a legacy achieved_sfia_level key instead; achievedTierFromTierResult (gradeYesNoSubmission.ts) reads both.

  commit;
