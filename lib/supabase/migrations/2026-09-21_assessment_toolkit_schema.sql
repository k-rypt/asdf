  -- Assessment-toolkit integration schema migration
  --
  -- Run this in the Supabase SQL editor (Dashboard > SQL Editor). The app only
  -- ever has the anon/publishable key at runtime, so this can't be applied
  -- programmatically from the repo -- it has to be pasted and run by hand.
  --
  -- Verified against the live schema via column/type probing on 2026-09-21:
  --   assessments.id            bigint
  --   assessments.created_by    uuid
  --   question_presets.id       bigint
  --   question_presets.capability_id  bigint
  --   attempt_answers.id        bigint
  --   attempt_answers.question_id  ** timestamp with time zone ** (bug, see step 0)
  --   questions.id               uuid
  --   questions.capability_id    bigint
  --   capabilities.id            bigint
  --   profile_capabilities.profile_id     uuid
  --   profile_capabilities.capability_id  bigint
  --
  -- Before running: confirm `attempt_answers` has zero rows (SQL editor:
  -- `select count(*) from attempt_answers;`). Step 0 below assumes that --
  -- if there's real data in that column already, do NOT run step 0 as-is,
  -- since a timestamptz value can't be cast to uuid. Tell me and we'll
  -- write a backfill instead.

  begin;

  -- ---------------------------------------------------------------------
  -- Step 0: fix attempt_answers.question_id -- it was created as
  -- timestamptz instead of uuid, so it has never actually matched
  -- questions.id. This is what backs the "Total Attempts" / sub-score
  -- stats on the admin question-detail page.
  -- ---------------------------------------------------------------------
  alter table public.attempt_answers
    alter column question_id drop default; -- old timestamptz default (likely now()) can't cast to uuid

  alter table public.attempt_answers
    alter column question_id type uuid using null; -- column is empty; drop the bad values

  alter table public.attempt_answers
    add constraint attempt_answers_question_id_fkey
    foreign key (question_id) references public.questions(id) on delete cascade;

  -- ---------------------------------------------------------------------
  -- Step 1: a parent `attempts` table -- one row per employee's run
  -- through an assessment. attempt_answers becomes per-question detail
  -- rows underneath it (session-level timing/status lives here, not
  -- duplicated across every answer row).
  -- ---------------------------------------------------------------------
  create table if not exists public.attempts (
    id bigint generated by default as identity primary key,
    assessment_id bigint not null references public.assessments(id) on delete cascade,
    profile_id uuid not null references public.profiles(id) on delete cascade,
    status text not null default 'in_progress', -- in_progress | completed | invalidated
    started_at timestamptz not null default now(),
    completed_at timestamptz,
    passed boolean,
    created_at timestamptz not null default now()
  );

  alter table public.attempt_answers
    add column if not exists attempt_id bigint references public.attempts(id) on delete cascade;

  -- New tables default to RLS *disabled* in Postgres -- without this, the
  -- anon/publishable key the app uses at runtime could read/write every
  -- row in `attempts` for every employee.
  --
  -- Policy style below matches what's already on `questions` (confirmed via
  -- pg_policies): name-based role join through profile_roles -> roles,
  -- gating writes to 'admin' / 'capability owner'. Unlike the existing
  -- tables, `attempts` also gets owner-scoped policies (auth.uid() =
  -- profile_id) since -- unlike profile_roles/profile_capabilities, which
  -- only admins manage -- an employee legitimately needs to create/update
  -- their own attempt. This is a new pattern relative to the rest of the
  -- schema, called out here rather than silently introduced.
  alter table public.attempts enable row level security;

  create policy "Employees can view their own attempts"
    on public.attempts for select
    to authenticated
    using (profile_id = auth.uid());

  create policy "Employees can insert their own attempts"
    on public.attempts for insert
    to authenticated
    with check (profile_id = auth.uid());

  create policy "Employees can update their own in-progress attempts"
    on public.attempts for update
    to authenticated
    using (profile_id = auth.uid())
    with check (profile_id = auth.uid());

  -- Needed for the admin capability/question analytics pages, which must
  -- see every employee's attempts, not just their own.
  create policy "Admin or capability owner can view all attempts"
    on public.attempts for select
    to authenticated
    using (
      exists (
        select 1 from profile_roles pr
        join roles r on pr.profile_role = r.id
        where pr.profile_id = auth.uid()
          and r.name = any (array['admin', 'capability owner'])
      )
    );

  -- ---------------------------------------------------------------------
  -- Step 1b: attempt_answers currently has RLS enabled with only a broad
  -- "Allow authenticated select" policy (any signed-in user can read every
  -- employee's scores) and NO insert/update/delete policy at all -- meaning
  -- no submission can be written through the client today.
  --
  -- This replaces that broad select policy with two owner-scoped ones
  -- (own attempt, or admin/capability owner -- mirroring the `attempts`
  -- policies above), and adds the missing insert policy scoped to "you own
  -- the parent attempt" via the attempt_id column added in step 1.
  -- ---------------------------------------------------------------------
  drop policy if exists "Allow authenticated select" on public.attempt_answers;

  create policy "Employees can view answers for their own attempt"
    on public.attempt_answers for select
    to authenticated
    using (
      exists (
        select 1 from public.attempts a
        where a.id = attempt_answers.attempt_id
          and a.profile_id = auth.uid()
      )
    );

  create policy "Admin or capability owner can view all attempt answers"
    on public.attempt_answers for select
    to authenticated
    using (
      exists (
        select 1 from profile_roles pr
        join roles r on pr.profile_role = r.id
        where pr.profile_id = (select auth.uid())
          and r.name = any (array['admin', 'capability owner'])
      )
    );

  create policy "Employees can insert answers for their own attempt"
    on public.attempt_answers for insert
    to authenticated
    with check (
      exists (
        select 1 from public.attempts a
        where a.id = attempt_answers.attempt_id
          and a.profile_id = auth.uid()
      )
    );

  -- ---------------------------------------------------------------------
  -- Step 2: customization columns on `assessments` (duration, passing
  -- score, which question types to include, which capability it belongs
  -- to, and a draft/published lifecycle).
  -- ---------------------------------------------------------------------
  alter table public.assessments
    add column if not exists capability_id bigint references public.capabilities(id) on delete set null,
    add column if not exists duration_minutes integer,
    add column if not exists passing_score numeric,
    add column if not exists question_type_mix jsonb, -- e.g. {"code_snippet": 3, "multiple_choice": 5, "yes_no": 2}
    add column if not exists status text not null default 'draft'; -- draft | published | archived

  -- ---------------------------------------------------------------------
  -- Step 3: mirror the same customization columns on `question_presets`,
  -- so a preset is a reusable template an assessment can be created from
  -- (capabilities.current_preset already points at a row here).
  -- ---------------------------------------------------------------------
  alter table public.question_presets
    add column if not exists duration_minutes integer,
    add column if not exists passing_score numeric,
    add column if not exists question_type_mix jsonb;

  -- ---------------------------------------------------------------------
  -- Step 4: fixed question set per assessment (assessment_questions).
  -- A capability lead picks/approves an exact list of questions rather
  -- than the assessment adaptively pulling from the whole bank.
  -- ---------------------------------------------------------------------
  create table if not exists public.assessment_questions (
    id bigint generated by default as identity primary key,
    assessment_id bigint not null references public.assessments(id) on delete cascade,
    question_id uuid not null references public.questions(id) on delete cascade,
    position integer not null default 0,
    unique (assessment_id, question_id)
  );

  alter table public.assessment_questions enable row level security;

  -- Matches the "Allow authenticated select" style already used on
  -- questions/question_choices/profile_roles (attempt_answers had this
  -- same policy until step 1b above replaced it with owner-scoped ones).
  create policy "Allow authenticated select"
    on public.assessment_questions for select
    to public
    using (auth.role() = 'authenticated');

  -- Matches the exact admin/capability-owner write-gating already on
  -- `questions` (name-based join through profile_roles -> roles).
  create policy "Admin or capability owner can manage assessment questions"
    on public.assessment_questions for all
    to authenticated
    using (
      exists (
        select 1 from profile_roles pr
        join roles r on pr.profile_role = r.id
        where pr.profile_id = (select auth.uid())
          and r.name = any (array['admin', 'capability owner'])
      )
    )
    with check (
      exists (
        select 1 from profile_roles pr
        join roles r on pr.profile_role = r.id
        where pr.profile_id = (select auth.uid())
          and r.name = any (array['admin', 'capability owner'])
      )
    );

  -- ---------------------------------------------------------------------
  -- Step 5: question authoring lifecycle. AI-drafted questions land as
  -- 'pending_review' and must be promoted by a capability lead -- never
  -- auto-published into the live bank.
  --
  -- `status` and `type` on `questions` turned out to be enum types
  -- (question_status, question_type), not text columns with a check
  -- constraint -- confirmed via pg_constraint (0 rows) and
  -- information_schema.columns (data_type = USER-DEFINED). Adding a new
  -- enum value uses `alter type ... add value`, which Postgres will not
  -- allow inside this transaction block (a newly added enum value can't
  -- be used in the same transaction it was created in, and some Postgres
  -- versions disallow the ALTER itself inside an open transaction).
  --
  -- See the separate, non-transactional file:
  --   2026-09-21_assessment_toolkit_schema_02_question_enums.sql
  -- Run each statement in it one at a time.
  -- ---------------------------------------------------------------------

  -- ---------------------------------------------------------------------
  -- Step 6: track who authored a question and how (manual vs AI-generated),
  -- useful for the review queue UI.
  -- ---------------------------------------------------------------------
  alter table public.questions
    add column if not exists created_by uuid references public.profiles(id) on delete set null,
    add column if not exists source text not null default 'manual'; -- manual | ai_generated | ai_extracted

  commit;
