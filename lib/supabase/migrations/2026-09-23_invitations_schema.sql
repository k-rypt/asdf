-- ============================================================
-- Invitations & Invitation Capabilities
-- ============================================================
-- The `invitation_status` enum (pending, claimed, expired) was
-- created in the original assessment toolkit schema migration.

-- Main invitations table
CREATE TABLE IF NOT EXISTS invitations (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token       uuid DEFAULT gen_random_uuid() NOT NULL UNIQUE,
  email       text NOT NULL,
  given_name  text NOT NULL,
  last_name   text NOT NULL,
  job_title   text,
  department_id bigint REFERENCES departments(id) ON DELETE SET NULL,
  assigned_roles bigint[] NOT NULL DEFAULT '{}',
  status      invitation_status NOT NULL DEFAULT 'pending',
  created_at  timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz NOT NULL DEFAULT (now() + interval '7 days')
);

-- Junction table: capabilities assigned to an invitation
CREATE TABLE IF NOT EXISTS invitation_capabilities (
  invitation_id bigint NOT NULL REFERENCES invitations(id) ON DELETE CASCADE,
  capability_id bigint NOT NULL REFERENCES capabilities(id) ON DELETE CASCADE,
  PRIMARY KEY (invitation_id, capability_id)
);

-- ============================================================
-- Row-Level Security
-- ============================================================

ALTER TABLE invitations ENABLE ROW LEVEL SECURITY;
ALTER TABLE invitation_capabilities ENABLE ROW LEVEL SECURITY;

-- Admins: full CRUD on invitations
CREATE POLICY "Admins can manage invitations"
  ON invitations FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM profile_roles
      WHERE profile_roles.profile_id = auth.uid()
        AND profile_roles.profile_role = 1
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM profile_roles
      WHERE profile_roles.profile_id = auth.uid()
        AND profile_roles.profile_role = 1
    )
  );

-- All authenticated users can view invitations (for their own status checks)
CREATE POLICY "Authenticated users can view invitations"
  ON invitations FOR SELECT
  USING (auth.role() = 'authenticated');

-- Admins: full CRUD on invitation_capabilities
CREATE POLICY "Admins can manage invitation capabilities"
  ON invitation_capabilities FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM profile_roles
      WHERE profile_roles.profile_id = auth.uid()
        AND profile_roles.profile_role = 1
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM profile_roles
      WHERE profile_roles.profile_id = auth.uid()
        AND profile_roles.profile_role = 1
    )
  );

-- All authenticated users can view invitation_capabilities
CREATE POLICY "Authenticated users can view invitation capabilities"
  ON invitation_capabilities FOR SELECT
  USING (auth.role() = 'authenticated');
